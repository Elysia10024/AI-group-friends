// 「对方想收尾 / 要离场」的轻量识别 —— 只产出**软提示**，不做拦截。
//
// 为什么需要它（2026-09-19 真实教训）：老秦说了句「nonono我要洗澡了，回来再跟你唠」——
// 那是递台阶、想把话题收住；她回了「行，去吧，别把脑子也一块冲下水道了」。
// 补了这一刀之后，对方一小时后又回来接着挑，才升级成那场大战。
// "我去洗澡了""不聊了""算了"是**明确的社会信号**，接不住就等于追着打；
// 群里都是朋友，平时损着玩没事，真吵起来了必须收得住。
//
// 取向刻意偏保守吗？不 —— 这里刻意**偏宽松**：它只往提示里加一句话
// （"对方可能想收尾……"），漏报的代价是那场架又续上，误报的代价只是多一句提醒。
// 所以宁可多认一点，也不做脆弱的精确匹配；真正的行为约束写在角色卡里。

// 明确的收尾/认输/换话题说法。
const LEAVE_WORD_RE = /(拜拜|晚安|下次(再)?(聊|说)|回头(再)?(聊|说)|晚点(再)?(聊|说)|改天(再)?聊|不聊了|不说了|说完了|到此为止|打住|停(了|吧)|算了|行吧|行行行|你赢了|当我没说|换个话题|说点别的|先这样|就这样吧)/;

// 离场动作（要配合第一人称/意愿词，避免"上班好累"这类陈述被当成要走了）。
const LEAVE_ACT_RE = /(洗个?澡|冲个?澡|吃饭|干饭|睡(觉|了|吧|一会|一觉)|困了|休息|躺(一|会)|出门|上班|下班|上课|开会|干活|忙(一会|一会儿)|溜了|走了|下线|下了)/;

// 第一人称 / 意愿词：出现它才认为"是在说自己要走"，而不是在评价别人。
const INTENT_RE = /(我|先|得|要|该|准备|回|去)/;

// 状态陈述，而不是"要走了"：『我今天上班好累』『上课好烦』这类不是离场信号。
// 但**不能因为出现状态词就一律排除**：『今天真的累了，先睡了』恰恰是在告别。
// 所以只看词序 —— 状态词在离场动作**后面**才算"在抱怨状态"（上班…好累），
// 在**前面**则是"因为累所以走了"（累了，先睡了）。
const STATE_TALK_RE = /(好累|累了|很累|好烦|好困|困死|难受|不爽|好开心|无聊)/;

/**
 * 这条消息是不是"我要收尾/离场"的信号。
 * @param {string} text
 * @returns {boolean}
 */
export function looksLikeTopicEnd(text) {
  const s = String(text ?? '').trim();
  if (!s) return false;
  // 长消息不太可能是"我去洗澡了"这种一句话收尾；这里也顺手挡掉正文里恰好出现这些词的情况。
  if (s.length > 60) return false;
  if (LEAVE_WORD_RE.test(s)) return true;
  const act = LEAVE_ACT_RE.exec(s);
  if (!act) return false;
  const state = STATE_TALK_RE.exec(s);
  if (state && state.index > act.index) return false;
  return INTENT_RE.test(s);
}
